#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct DnsProvisioningBundle {
    pub domain: String,
    pub umail_client_url: String,
    pub records: Vec<DnsRecordEntry>,
}

impl DnsProvisioningBundle {
    pub fn to_bind_zone(&self) -> String {
        let mut out = format!(
            "; ============================================================================\n; BIND Zone File for {}\n; Generated by ka-posong Multi-Tenant Mail Suite & Cloudflare Edge Ingress\n; ============================================================================\n$TTL 300\n@ IN SOA ns1.cloudflare.com. hostmaster.{}. ( {} 7200 3600 1209600 300 )\n@ IN NS ns1.cloudflare.com.\n@ IN NS ns2.cloudflare.com.\n\n",
            self.domain,
            self.domain,
            chrono::Utc::now().format("%Y%m%d01")
        );
        for r in &self.records {
            let host = if r.host == "@" { "@".to_string() } else { r.host.clone() };
            if r.record_type == "MX" {
                let prio = r.priority.unwrap_or(10);
                out.push_str(&format!("{:<24} IN MX {:<4} {}.\n", host, prio, r.value.trim_end_matches('.')));
            } else if r.record_type == "TXT" {
                out.push_str(&format!("{:<24} IN TXT \"{}\"\n", host, r.value));
            } else if r.record_type == "CNAME" {
                out.push_str(&format!("{:<24} IN CNAME {}.\n", host, r.value.trim_end_matches('.')));
            }
        }
        out
    }

    pub fn to_cloudflare_csv(&self) -> String {
        let mut out = String::from("Type,Name,Content,TTL,Priority,Proxy status\n");
        for r in &self.records {
            let prio_str = r.priority.map(|p| p.to_string()).unwrap_or_default();
            out.push_str(&format!(
                "{},{},\"{}\",300,{},false\n",
                r.record_type, r.host, r.value, prio_str
            ));
        }
        out
    }
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct DnsRecordEntry {
    pub record_type: String,
    pub host: String,
    pub value: String,
    pub priority: Option<u16>,
    pub purpose: String,
}

pub fn build_dns_bundle(
    domain: &str,
    primary_mail_hostname: &str,
    dkim_selector: &str,
    dkim_public_key: &str,
) -> DnsProvisioningBundle {
    DnsProvisioningBundle {
        domain: domain.to_string(),
        umail_client_url: format!("https://{}/umail", domain),
        records: vec![
            // 1. Cloudflare Email Routing Primary Inbound MX Records
            DnsRecordEntry {
                record_type: "MX".into(),
                host: "@".into(),
                value: "route1.mx.cloudflare.net".into(),
                priority: Some(70),
                purpose: "Cloudflare Email Routing Primary Inbound (Port 25 -> Worker HTTPS Ingest)".into(),
            },
            DnsRecordEntry {
                record_type: "MX".into(),
                host: "@".into(),
                value: "route2.mx.cloudflare.net".into(),
                priority: Some(52),
                purpose: "Cloudflare Email Routing Secondary Inbound MX".into(),
            },
            DnsRecordEntry {
                record_type: "MX".into(),
                host: "@".into(),
                value: "route3.mx.cloudflare.net".into(),
                priority: Some(56),
                purpose: "Cloudflare Email Routing Tertiary Inbound MX".into(),
            },
            // 2. Cloudflare Email Sending Service Bounce MX Records
            DnsRecordEntry {
                record_type: "MX".into(),
                host: "cf-bounce".into(),
                value: "route1.mx.cloudflare.net".into(),
                priority: Some(70),
                purpose: "Cloudflare Email Sending Service Outbound Bounce Receiver".into(),
            },
            DnsRecordEntry {
                record_type: "MX".into(),
                host: "cf-bounce".into(),
                value: "route2.mx.cloudflare.net".into(),
                priority: Some(52),
                purpose: "Cloudflare Email Sending Service Outbound Bounce Secondary".into(),
            },
            DnsRecordEntry {
                record_type: "MX".into(),
                host: "cf-bounce".into(),
                value: "route3.mx.cloudflare.net".into(),
                priority: Some(56),
                purpose: "Cloudflare Email Sending Service Outbound Bounce Tertiary".into(),
            },
            // 3. SPF Authentication TXT
            DnsRecordEntry {
                record_type: "TXT".into(),
                host: "@".into(),
                value: format!(
                    "v=spf1 include:_spf.mx.cloudflare.net a:{} ~all",
                    primary_mail_hostname
                ),
                priority: None,
                purpose: "SPF Sender Authorization (Cloudflare Edge + Tailscale Host)".into(),
            },
            // 4. DKIM Cryptographic Signature TXT
            DnsRecordEntry {
                record_type: "TXT".into(),
                host: format!("{}._domainkey", dkim_selector),
                value: dkim_public_key.to_string(),
                priority: None,
                purpose: "Stalwart Cryptographic DKIM Public Signing Key".into(),
            },
            // 5. DMARC Alignment & Policy TXT
            DnsRecordEntry {
                record_type: "TXT".into(),
                host: "_dmarc".into(),
                value: format!("v=DMARC1; p=quarantine; rua=mailto:postmaster@{}", domain),
                priority: None,
                purpose: "DMARC Anti-Spoofing & Alignment Policy".into(),
            },
            // 6. Custom Domain Webmail / JMAP CNAME
            DnsRecordEntry {
                record_type: "CNAME".into(),
                host: "webmail".into(),
                value: primary_mail_hostname.to_string(),
                priority: None,
                purpose: "Custom Domain Webmail & JMAP Gateway Endpoint".into(),
            },
        ],
    }
}

